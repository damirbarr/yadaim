// Copies the owner's traced logo (components/logo-paths.ts, the app's single source) into src/logo-paths.js,
// because the video page loads plain browser modules. Run after the logo changes: node sync-logo.mjs
import { readFile, writeFile } from "node:fs/promises";
const src = await readFile(new URL("../components/logo-paths.ts", import.meta.url), "utf8");
await writeFile(new URL("./src/logo-paths.js", import.meta.url), "// GENERATED by video/sync-logo.mjs from components/logo-paths.ts. Do not edit.\n" + src);
console.log("src/logo-paths.js");
